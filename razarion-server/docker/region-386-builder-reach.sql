-- Quest 386 (Dockyard in a region): the coast strip now ends 12 units out from the shore instead of 18, so every
-- spot the placer accepts in it can be reached by the builder.
--
-- A builder builds on the water from at most 15 units (BuilderType.rangeOtherTerrain), measured edge to edge:
-- centre distance minus the builder's radius (1.45) minus the Dockyard's (2). Standing on land, it reaches a Dockyard
-- centre about 17 units from the shore. The old strip ran 18 out, and the placer only checks region, water, items
-- and enemies - not the builder's reach. A Dockyard placed out there turned the build into a plain move
-- (CommandService.build -> moveIfPathTargetUnreachable): the builder drove to the beach and stopped, no site, no
-- message, the tip back at "select the builder" (phone test, 2026-10-07).
--
-- Computed from the PROD heightmap of 2026-10-07 (same shore scan as region-386-north-coast.sql, outer edge +12):
-- old strip 158 of 4725 Dockyard centres out of reach (worst 22.7 against 15), new strip none (worst 10.6).
-- 23 of the 29 Docks built by players who passed since 2026-10-04 lie in it.
--
-- Looks the region up through quest 386, so it runs the same on local and PROD. A player with 386 active keeps
-- the old region until reload.

